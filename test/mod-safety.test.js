import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, "..");
const mainJsPath = path.join(rootDir, "mods/docker-manager/main.js");
const logicJsPath = path.join(rootDir, "mods/docker-manager/docker-logic.js");
const dtsPath = path.join(rootDir, "mods/docker-manager/gpui-kit.d.ts");
const iconsDir = path.join(rootDir, "mods/docker-manager/icons");

// Explicitly allowed dead assets in icons/
const ALLOWED_DEAD_ASSETS = new Set([
  "whale.svg",
  "image.svg",
  "system.svg",
  "hammer.svg",
]);

test("mod-safety: chained method calls in main.js are valid GPUI, mod, or JS methods", (t) => {
  if (!fs.existsSync(dtsPath)) {
    t.skip("mods/docker-manager/gpui-kit.d.ts is absent (generated by herdr-app check)");
    return;
  }

  const mainCode = fs.readFileSync(mainJsPath, "utf8");
  const callRegex = /\.([a-z][a-z0-9_]+)\s*\(/g;
  const calls = new Set();
  let m;
  while ((m = callRegex.exec(mainCode)) !== null) {
    calls.add(m[1]);
  }

  assert.ok(calls.size > 0, "Expected to find chained method calls in main.js");

  const dts = fs.readFileSync(dtsPath, "utf8");
  const dtsMethods = new Set();
  const dtsRegex = /(?:^\s*|\b)([a-z][a-z0-9_]+)\s*(?:<[^>]*>)?\s*\(/gm;
  while ((m = dtsRegex.exec(dts)) !== null) {
    dtsMethods.add(m[1]);
  }
  const dtsPropRegex = /(?:^\s*|\b)([a-z][a-z0-9_]+)\s*\??:\s*(?:<[^>]*>)?\s*\(/gm;
  while ((m = dtsPropRegex.exec(dts)) !== null) {
    dtsMethods.add(m[1]);
  }

  const jsBuiltins = new Set([
    "assign", "entries", "keys", "values", "from", "isArray", "isInteger",
    "filter", "find", "findIndex", "findLast", "includes", "join", "map", "pop", "push",
    "slice", "some", "sort", "every", "reduce", "reduceRight", "concat", "flat", "flatMap", "indexOf", "lastIndexOf",
    "replace", "replaceAll", "split", "trim", "trimStart", "trimEnd", "toLowerCase", "toUpperCase", "startsWith", "endsWith",
    "match", "matchAll", "search", "charAt", "charCodeAt", "codePointAt", "repeat", "padStart", "padEnd",
    "min", "max", "floor", "ceil", "round", "abs", "sqrt", "random",
    "now", "parse", "stringify", "toISOString", "getTime",
    "add", "clear", "delete", "get", "has", "set", "forEach",
    "all", "allSettled", "race", "resolve", "reject", "then", "catch", "finally",
    "test", "exec", "toString", "valueOf", "toFixed", "toPrecision",
    "log", "warn", "error", "info", "debug",
  ]);

  const modMethods = new Set();
  const modRegex = /^\s*([a-z][a-z0-9_]+)\s*\(/gm;
  while ((m = modRegex.exec(mainCode)) !== null) {
    modMethods.add(m[1]);
  }

  const unknown = [];
  for (const c of Array.from(calls).sort()) {
    if (!dtsMethods.has(c) && !jsBuiltins.has(c) && !modMethods.has(c)) {
      unknown.push(c);
    }
  }

  assert.deepEqual(
    unknown,
    [],
    `Found invented or undeclared chained methods in main.js: ${unknown.join(", ")}`
  );
});

test("mod-safety: svg icons referenced from main.js exist on disk and all icons are accounted for", () => {
  const mainCode = fs.readFileSync(mainJsPath, "utf8");
  const logicCode = fs.existsSync(logicJsPath) ? fs.readFileSync(logicJsPath, "utf8") : "";

  const referenced = new Set();
  let m;

  // Direct paths: mods/docker-manager/icons/<name>.svg
  const directRegex = /mods\/docker-manager\/icons\/([a-zA-Z0-9_\-]+\.svg)/g;
  while ((m = directRegex.exec(mainCode)) !== null) {
    referenced.add(m[1]);
  }

  // Any literal "<name>.svg" in main.js and docker-logic.js (e.g. icon definitions)
  const literalSvgRegex = /["\x27\x60]([a-zA-Z0-9_\-]+\.svg)["\x27\x60]/g;
  while ((m = literalSvgRegex.exec(mainCode)) !== null) {
    referenced.add(m[1]);
  }
  while ((m = literalSvgRegex.exec(logicCode)) !== null) {
    referenced.add(m[1]);
  }

  assert.ok(fs.existsSync(iconsDir), "icons directory must exist");
  const filesOnDisk = fs.readdirSync(iconsDir).filter((f) => f.endsWith(".svg"));

  // 1. Every referenced icon must exist on disk
  const missingFromDisk = Array.from(referenced).filter((f) => !filesOnDisk.includes(f));
  assert.deepEqual(
    missingFromDisk,
    [],
    `Icons referenced in code but missing from disk: ${missingFromDisk.join(", ")}`
  );

  // 2. Every file on disk must be referenced or explicitly allowed as a dead asset
  const unreferenced = filesOnDisk.filter((f) => !referenced.has(f) && !ALLOWED_DEAD_ASSETS.has(f));
  assert.deepEqual(
    unreferenced,
    [],
    `Icons on disk that are neither referenced nor in ALLOWED_DEAD_ASSETS: ${unreferenced.join(", ")}`
  );
});
